/** GICS sector plus the geography the research applies to. */
export type DossierScope = SectorDossier['scope'];

/**
 * Picks the dossier that actually describes a company.
 *
 * A Brazilian distributor and an American one share a GICS label and almost
 * nothing else, so the country decides which research applies. Falling back to
 * a GLOBAL entry is correct where one exists — semiconductors really are one
 * market — and returning nothing is better than returning the wrong country's
 * regulator.
 */
export function findSectorDossier(
  sector: string,
  country: string,
  /**
   * Required rather than optional: several dossiers are scoped to specific
   * industries, so a caller that omits this silently gets nothing back for
   * exactly the sectors where the distinction matters most.
   */
  industry: string,
): SectorDossier | null {
  const scope: DossierScope =
    country === 'Brazil' ? 'BRAZIL' : country === 'United States' ? 'UNITED_STATES' : 'GLOBAL';
  const inSector = SECTOR_DOSSIERS.filter((d) => d.sector === sector);

  // An industry match is the strongest signal, then a dossier that claims the
  // whole sector. Country before GLOBAL in both cases, because the regulator
  // matters more than the taxonomy.
  const named = (s: DossierScope) =>
    inSector.find((d) => d.scope === s && d.industries?.includes(industry));
  const whole = (s: DossierScope) => inSector.find((d) => d.scope === s && !d.industries);

  return named(scope) ?? whole(scope) ?? named('GLOBAL') ?? whole('GLOBAL') ?? null;
}

export function dossiersForSector(sector: string): SectorDossier[] {
  return SECTOR_DOSSIERS.filter((d) => d.sector === sector);
}
